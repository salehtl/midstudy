"""Writes server/src/product/entities.ts: Python 3.12's `html.unescape` tables (html.entities.html5, and html's
_invalid_charrefs and _invalid_codepoints), so the TypeScript reader unescapes exactly as v1 did.
Run with the dev shell's Python: `nix develop -c python3 server/src/product/tools/gen_entities.py`."""
import html
import html.entities
import pathlib
import sys


def lit(s: str) -> str:
    out = []
    for ch in s:
        c = ord(ch)
        if ch in "'\\":
            out.append("\\" + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        else:
            out.append("\\u{%x}" % c)
    return "'" + "".join(out) + "'"


rows = ",\n".join(f"  [{lit(k)}, {lit(v)}]" for k, v in html.entities.html5.items())
charrefs = ", ".join(f"[{k}, {lit(v)}]" for k, v in sorted(html._invalid_charrefs.items()))
codepoints = ", ".join(str(c) for c in sorted(html._invalid_codepoints))
text = f"""// Generated by server/src/product/tools/gen_entities.py from Python {sys.version.split()[0]}: html.unescape's tables, as v1
// unescaped. Do not edit.

/** html.entities.html5: every HTML5 character reference name (with and without its ';') and its text. */
export const HTML5_ENTITIES: ReadonlyMap<string, string> = new Map([
{rows},
])

/** html._invalid_charrefs: numeric references the HTML5 spec maps elsewhere (0x80–0x9F as Windows-1252, NUL, CR). */
export const INVALID_CHARREFS: ReadonlyMap<number, string> = new Map([{charrefs}])

/** html._invalid_codepoints: numeric references unescape drops. */
export const INVALID_CODEPOINTS: ReadonlySet<number> = new Set([{codepoints}])
"""
path = pathlib.Path(__file__).resolve().parent.parent / "entities.ts"
path.write_text(text)
print(f"{path}: {len(html.entities.html5)} entities")
