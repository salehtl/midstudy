"""Writes server/src/product/charsets.ts: which codec Python 3.12's `codecs.lookup` finds for a charset name (v1's
`_charset`), after Python's own normalization (encodings.normalize_encoding and the aliases), and whether it is a text
encoding. Run with the dev shell's Python: `nix develop -c python3 server/src/product/tools/gen_charsets.py`."""
import codecs
import encodings
import encodings.aliases
import pathlib
import pkgutil
import sys

names = set(encodings.aliases.aliases) | {m.name for m in pkgutil.iter_modules(encodings.__path__)}
rows = {}
for n in sorted(names):
    try:
        info = codecs.lookup(n)
    except LookupError:
        continue
    rows[n] = (info.name, bool(getattr(info, "_is_text_encoding", True)))
body = ",\n".join(f"  ['{k}', ['{v[0]}', {'true' if v[1] else 'false'}]]" for k, v in rows.items())

# Single-byte (charmap) codecs: Python's own decoding tables (U+FFFE marks a byte the codec leaves undefined).
import importlib
tables = {}
for module in sorted({m.name for m in pkgutil.iter_modules(encodings.__path__)}):
    try:
        mod = importlib.import_module(f"encodings.{module}")
    except Exception:  # noqa: BLE001 - platform-specific codecs
        continue
    table = getattr(mod, "decoding_table", None)
    if isinstance(table, str) and len(table) == 256:
        tables[codecs.lookup(module).name] = table


def lit(t):
    return "'" + "".join(ch if 0x20 <= ord(ch) < 0x7F and ch not in "'\\" else "\\u{%x}" % ord(ch) for ch in t) + "'"


charmaps = ",\n".join(f"  ['{k}', {lit(v)}]" for k, v in sorted(tables.items()))
text = f"""// Generated by server/src/product/tools/gen_charsets.py from Python {sys.version.split()[0]}: the codec codecs.lookup finds for
// each normalized charset name (encodings.aliases and the codec modules), and whether it is a text encoding. Do not edit.

/** normalized name → [Python's codec name, a text encoding]. */
export const PY_CODECS: ReadonlyMap<string, readonly [string, boolean]> = new Map([
{body},
])

/** The single-byte codecs' decoding tables (256 characters each; U+FFFE is a byte the codec leaves undefined). */
export const CHARMAPS: ReadonlyMap<string, string> = new Map([
{charmaps},
])
"""
path = pathlib.Path(__file__).resolve().parent.parent / "charsets.ts"
path.write_text(text)
print(f"{path}: {len(rows)} names, {len(tables)} charmaps")
