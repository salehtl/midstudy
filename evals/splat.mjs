  const clickErr = await more.click({ timeout: 20000 }).then(() => null, (e) => String(e.message || e).split('\n').filter((l) => /intercepts|not visible|not stable|detached|outside|waiting for|Timeout/.test(l)).slice(-3).join(' / '))
