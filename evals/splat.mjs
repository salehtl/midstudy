// --- the splat probe: points on the faces of an 80 × 120 × 50 cm box, 1 cm apart, opaque magenta, about 6 mm each ---------
function splatBoxPly({ w, h, d }, step = 0.01) {
  const pts = []
  const faces = [[0, w, 1, h, 2, d], [2, d, 1, h, 0, w], [0, w, 2, d, 1, h]] // (u axis, u size, v axis, v size, fixed axis, fixed size)
  for (const [ua, us, va, vs, fa, fs_] of faces) {
    const nu = Math.round(us / step), nv = Math.round(vs / step)
    for (const side of [0, 1]) for (let i = 0; i <= nu; i++) for (let j = 0; j <= nv; j++) {
      const p = [0, 0, 0]
      p[ua] = (i / nu) * us; p[va] = (j / nv) * vs; p[fa] = side * fs_
      pts.push([p[0] - w / 2, p[1], p[2] - d / 2])
    }
  }
  const props = ['x', 'y', 'z', 'f_dc_0', 'f_dc_1', 'f_dc_2', 'opacity', 'scale_0', 'scale_1', 'scale_2', 'rot_0', 'rot_1', 'rot_2', 'rot_3']
  const C0 = 0.28209479177387814
  const dc = [(1 - 0.5) / C0, (0 - 0.5) / C0, (1 - 0.5) / C0]
  const ls = Math.log(0.006)
  const body = new Float32Array(pts.length * props.length)
  pts.forEach((p, k) => body.set([...p, ...dc, 5.3, ls, ls, ls, 1, 0, 0, 0], k * props.length))
  const header = `ply\nformat binary_little_endian 1.0\nelement vertex ${pts.length}\n${props.map((n) => `property float ${n}\n`).join('')}end_header\n`
  return { buf: Buffer.concat([Buffer.from(header, 'ascii'), Buffer.from(body.buffer)]), count: pts.length }
}
function addSplatProbe(libDir) {
  const { w, d, h } = SPROBE.dims_cm
  fs.mkdirSync(path.join(libDir, SPROBE.id), { recursive: true })
  fs.writeFileSync(path.join(libDir, SPROBE.id, 'model.glb'), boxGlb(w / 100, h / 100, d / 100, [0, 1, 0, 1])) // green: must never show
  const ply = splatBoxPly({ w: w / 100, h: h / 100, d: d / 100 })
  fs.writeFileSync(path.join(libDir, SPROBE.id, 'splat.ply'), ply.buf)
  const lib = JSON.parse(fs.readFileSync(path.join(libDir, 'library.json'), 'utf8'))
  lib.items.push({
    id: SPROBE.id, name: SPROBE.name, category: 'test', dims_cm: { w, d, h },
    assets: { glb: `${SPROBE.id}/model.glb`, splat: `${SPROBE.id}/splat.ply`, spz: null, thumb: null }, default_render: 'splat',
    source: { engine: 'fixture', input: 'generated by evals/splat.mjs', prompt: null, cost_usd: 0, mock: false, created: '2026-11-05T00:00:00Z' },
    notes: 'Eval probe: magenta splat box (PLY only), green stand-in GLB that must never be drawn.',
  })
  fs.writeFileSync(path.join(libDir, 'library.json'), JSON.stringify(lib, null, 2))
  return ply.count
}

