#!/usr/bin/env node
// Generates, from every JSON Schema of the contract (contract/*.schema.json, contract/api/*.schema.json):
//   contract/gen/types.ts              TypeScript types (export type, deeply readonly, no any)
//   contract/gen/validate.js, .d.ts    Ajv standalone validators (ESM), one typed type guard per named type, and
//                                      `validators` / `violation()` keyed by schema URI (for strict mode)
//   core/crates/contract/schema.json   the bundle (one draft-07 schema, every named type under definitions), which
//                                      the midstudy-contract crate's build.rs turns into serde types with typify
// Deterministic and idempotent: same schemas in, same bytes out. Never edit the outputs by hand.
//
// Usage: node scripts/gen-contract.mjs            write the outputs
//        node scripts/gen-contract.mjs --check    regenerate in memory; exit 1 if any output differs from disk
//
// Named types: a schema's root (its title when that is an identifier such as SceneObject, else the file name in
// PascalCase: calib.schema.json → Calib), every $defs entry (its title, else <File><Key>), and every inline subschema
// whose title is an identifier (e.g. AlignResult). $defs that are the same apart from annotations (the camera block in
// calib.schema.json and scene.schema.json) become one type. Refs into a schema's properties (scene-detail reusing the
// scene object's fields) are inlined.
//
// For the types (TS and Rust), validation-only constraints are dropped: `not`, keys that must be absent, branches of
// anyOf/oneOf that only say which keys are required. The types are therefore a little looser than the validators
// (patterns, ranges, publicCalib's missing make/model); the validators are exact.
import fs from 'node:fs'
import path from 'node:path'
import standaloneCode from 'ajv/dist/standalone/index.js'
import { DATE_TIME, REPO, loadSchemas, makeAjv } from '../contract/tools/schemas.mjs'

const OUT = {
  types: path.join(REPO, 'contract/gen/types.ts'),
  validate: path.join(REPO, 'contract/gen/validate.js'),
  validateDts: path.join(REPO, 'contract/gen/validate.d.ts'),
  bundle: path.join(REPO, 'core/crates/contract/schema.json'),
}
const HEADER = 'Generated by scripts/gen-contract.mjs from contract/*.schema.json and contract/api/*.schema.json. Do not edit.'

// --- names ---------------------------------------------------------------------------------------------------------
const IDENT = /^[A-Z][A-Za-z0-9]*$/
const pascal = (s) => String(s).replace(/\.schema\.json$/, '').split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('')
const ANNOTATIONS = new Set(['description', '$comment', 'examples', '$schema', '$id'])
const SHAPE = ['type', '$ref', 'properties', 'items', 'enum', 'const', 'anyOf', 'oneOf', 'allOf', 'additionalProperties']
const clone = (v) => JSON.parse(JSON.stringify(v))
const canon = (v) => (Array.isArray(v) ? v.map(canon) : v && typeof v === 'object'
  ? Object.fromEntries(Object.keys(v).filter((k) => !ANNOTATIONS.has(k)).sort().map((k) => [k, canon(v[k])])) : v)
const same = (a, b) => JSON.stringify(canon(a)) === JSON.stringify(canon(b))

// URI handling: every $id is "midstudy/<file>"; a $ref is resolved against the $id of the schema it appears in.
function resolveRef(base, ref) {
  const [p, frag = ''] = ref.split('#')
  if (!p) return { id: base, pointer: frag }
  const dir = base.split('/').slice(0, -1)
  for (const seg of p.split('/')) {
    if (seg === '..') dir.pop()
    else if (seg !== '.') dir.push(seg)
  }
  return { id: dir.join('/'), pointer: frag }
}
const pointerGet = (doc, pointer) => pointer.split('/').filter(Boolean).reduce((o, k) => {
  const key = decodeURIComponent(k).replace(/~1/g, '/').replace(/~0/g, '~')
  if (o == null || !(key in o)) throw new Error(`no ${pointer}`)
  return o[key]
}, doc)

// --- the bundle -----------------------------------------------------------------------------------------------------
export function buildBundle(schemas) {
  const byId = new Map(schemas.map(({ schema }) => [schema.$id, schema]))
  // 1. every named location: `${id}#${pointer}` → name
  const named = new Map()
  const nameOf = (id, pointer, title, key) => {
    if (typeof title === 'string' && IDENT.test(title)) return title
    const file = pascal(path.basename(id))
    return pointer ? `${file}${pascal(key)}` : file
  }
  for (const { schema } of schemas) {
    const id = schema.$id
    const isContainer = !SHAPE.some((k) => k in schema)
    if (!isContainer) named.set(`${id}#`, nameOf(id, '', schema.title))
    for (const [key, def] of Object.entries(schema.$defs || {})) named.set(`${id}#/$defs/${key}`, nameOf(id, `/$defs/${key}`, def.title, key))
    // inline subschemas titled with an identifier
    const walk = (node, pointer) => {
      if (!node || typeof node !== 'object') return
      if (Array.isArray(node)) { node.forEach((n, i) => walk(n, `${pointer}/${i}`)); return }
      if (pointer && !pointer.startsWith('/$defs/') && typeof node.title === 'string' && IDENT.test(node.title)) named.set(`${id}#${pointer}`, node.title)
      if (pointer.startsWith('/$defs/') && pointer.split('/').length > 3 && typeof node.title === 'string' && IDENT.test(node.title)) named.set(`${id}#${pointer}`, node.title)
      for (const [k, v] of Object.entries(node)) if (k !== '$defs' || pointer === '') walk(v, `${pointer}/${k}`)
    }
    walk(schema, '')
  }
  // 2. rewrite each named location into a definition
  const defs = new Map() // name → {schema, from}
  const rewrite = (node, id, pointer, top) => {
    if (!node || typeof node !== 'object') return node
    if (Array.isArray(node)) return node.map((n, i) => rewrite(n, id, `${pointer}/${i}`, false))
    if (!top && named.has(`${id}#${pointer}`)) return { $ref: `#/definitions/${named.get(`${id}#${pointer}`)}` }
    const out = {}
    for (const [k, v] of Object.entries(node)) {
      if (k === '$defs' || k === '$id' || k === '$schema' || (k === 'title' && !top)) continue
      if (k === 'title') continue
      if (k === '$ref') {
        const t = resolveRef(id, v)
        const key = `${t.id}#${t.pointer}`
        if (named.has(key)) { out.$ref = `#/definitions/${named.get(key)}`; continue }
        const doc = byId.get(t.id)
        if (!doc) throw new Error(`${id}#${pointer}: $ref ${v} names no schema`)
        const target = pointerGet(doc, t.pointer)
        if (target && typeof target === 'object' && target.properties) throw new Error(`${id}#${pointer}: $ref ${v} points into an object schema: give it a $defs entry`)
        Object.assign(out, rewrite(target, t.id, t.pointer, false))
        continue
      }
      if (['properties', '$defs', 'definitions'].includes(k)) {
        out[k] = Object.fromEntries(Object.entries(v).map(([pk, pv]) => [pk, rewrite(pv, id, `${pointer}/${k}/${pk}`, false)]))
      } else if (v && typeof v === 'object') out[k] = rewrite(v, id, `${pointer}/${k}`, false)
      else out[k] = v
    }
    return out
  }
  for (const [loc, name] of [...named.entries()]) {
    const [id, pointer] = loc.split('#')
    const body = rewrite(pointer ? pointerGet(byId.get(id), pointer) : byId.get(id), id, pointer, true)
    const prev = defs.get(name)
    if (prev) {
      if (!same(prev.schema, body)) throw new Error(`two different schemas are both named ${name}: ${prev.from} and ${loc}`)
      continue
    }
    defs.set(name, { schema: body, from: loc })
  }
  const definitions = Object.fromEntries([...defs.keys()].sort().map((n) => [n, defs.get(n).schema]))
  return { $schema: 'http://json-schema.org/draft-07/schema#', $comment: HEADER, definitions }
}

// Drops what types can't say (see the header). Returns a new bundle.
export function simplifyForTypes(bundle) {
  const keys = (s) => Object.keys(s).filter((k) => !ANNOTATIONS.has(k))
  const isEmpty = (s) => s && typeof s === 'object' && !Array.isArray(s) && keys(s).length === 0
  // nothing but type: object (implied by a sibling $ref in an allOf)
  const isBareObject = (s) => s && typeof s === 'object' && keys(s).every((k) => k === 'type' && s.type === 'object')
  const assertionOnly = (s) => s && typeof s === 'object' && !SHAPE.some((k) => k in s)
  const simp = (s) => {
    if (!s || typeof s !== 'object') return s
    if (Array.isArray(s)) return s.map(simp)
    const out = {}
    for (const [k, v] of Object.entries(s)) {
      if (k === 'not') continue
      if (k === 'properties') out.properties = Object.fromEntries(Object.entries(v).filter(([, pv]) => pv !== false).map(([pk, pv]) => [pk, simp(pv)]))
      else out[k] = simp(v)
    }
    for (const k of ['anyOf', 'oneOf']) {
      if (!out[k]) continue
      out[k] = out[k].filter((m) => !assertionOnly(m))
      if (out[k].length === 0) delete out[k]
    }
    if (out.allOf) {
      let members = out.allOf.map((m) => {
        if (!m.properties) return m
        const r = { ...m, properties: Object.fromEntries(Object.entries(m.properties).filter(([, pv]) => !isEmpty(pv))) }
        if (Object.keys(r.properties).length === 0) delete r.properties
        return r
      })
      if (members.some((m) => m.$ref)) members = members.filter((m) => !isBareObject(m))
      delete out.allOf
      if (members.length === 1) Object.assign(out, members[0])
      else out.allOf = members
    }
    return out
  }
  return { ...bundle, definitions: Object.fromEntries(Object.entries(bundle.definitions).map(([n, s]) => [n, simp(s)])) }
}

// The bundle typify reads: no annotations beside a $ref, and an open object with properties gets
// additionalProperties: {} (as permissive as leaving it out), which makes typify keep the keys it doesn't model in a
// flattened `extra` map instead of dropping them (calib.json and lighting.json diagnostics survive a round trip).
function forRust(bundle) {
  const strip = (s) => {
    if (!s || typeof s !== 'object') return s
    if (Array.isArray(s)) return s.map(strip)
    if (s.$ref) return { $ref: s.$ref }
    const out = Object.fromEntries(Object.entries(s).map(([k, v]) => [k, k === 'properties' || k === 'definitions' ? Object.fromEntries(Object.entries(v).map(([pk, pv]) => [pk, strip(pv)])) : strip(v)]))
    if (out.properties && Object.keys(out.properties).length && (out.additionalProperties === undefined || out.additionalProperties === true)) out.additionalProperties = {}
    return out
  }
  return strip(bundle)
}

// --- TypeScript -----------------------------------------------------------------------------------------------------
const PROP = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const doc = (text, indent) => (text ? `${indent}/** ${String(text).replace(/\*\//g, '* /').replace(/\n/g, ' ')} */\n` : '')
export function typescript(bundle) {
  const t = (s, indent) => {
    if (s === true || s === undefined) return 'unknown'
    if (s === false) return 'never'
    if (s.$ref) return s.$ref.replace('#/definitions/', '')
    if ('const' in s) return JSON.stringify(s.const)
    if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ')
    if (s.anyOf || s.oneOf) {
      if (s.type || s.properties) throw new Error(`anyOf/oneOf beside type or properties isn't supported by the TS generator: ${JSON.stringify(s).slice(0, 200)}`)
      return (s.anyOf || s.oneOf).map((m) => wrap(t(m, indent))).join(' | ')
    }
    if (s.allOf) return s.allOf.map((m) => wrap(t(m, indent))).join(' & ')
    const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : s.properties ? ['object'] : []
    if (types.length === 0) return 'unknown'
    return types.map((ty) => wrap(one(ty, s, indent))).join(' | ')
  }
  // parenthesize a union or intersection that is about to be combined (| or & outside any brackets)
  const wrap = (x) => {
    let depth = 0
    for (const c of x) {
      if ('{[(<'.includes(c)) depth++
      else if ('}])>'.includes(c)) depth--
      else if (depth === 0 && (c === '|' || c === '&')) return `(${x})`
    }
    return x
  }
  const one = (ty, s, indent) => {
    switch (ty) {
      case 'string': return 'string'
      case 'number': case 'integer': return 'number'
      case 'boolean': return 'boolean'
      case 'null': return 'null'
      case 'array': {
        const item = t(s.items, indent)
        if (s.minItems != null && s.minItems === s.maxItems && s.maxItems <= 9) return `readonly [${Array(s.maxItems).fill(item).join(', ')}]`
        return /^[A-Za-z0-9]+$/.test(item) ? `readonly ${item}[]` : `ReadonlyArray<${item}>`
      }
      case 'object': {
        const props = s.properties || {}
        const req = new Set(s.required || [])
        const inner = `${indent}  `
        const lines = Object.entries(props).map(([k, v]) => `${doc(v.description, inner)}${inner}readonly ${PROP.test(k) ? k : JSON.stringify(k)}${req.has(k) ? '' : '?'}: ${t(v, inner)}`)
        if (s.additionalProperties !== false) lines.push(`${inner}readonly [key: string]: ${s.additionalProperties && s.additionalProperties !== true && Object.keys(props).length === 0 ? t(s.additionalProperties, inner) : 'unknown'}`)
        return lines.length ? `{\n${lines.join('\n')}\n${indent}}` : '{ readonly [key: string]: never }'
      }
      default: throw new Error(`unknown type ${ty}`)
    }
  }
  let out = `// ${HEADER}\n// Every type is deeply readonly: payloads and files are values; build a new one to change it.\n`
  for (const [name, s] of Object.entries(bundle.definitions)) {
    out += `\n${doc(s.description, '')}export type ${name} = ${t(s, '')}\n`
  }
  return out
}

// --- validators -----------------------------------------------------------------------------------------------------
// The standalone helper ajv would require() at runtime (string length in code points), inlined so the module is
// plain ESM for Node and the browser bundle alike.
const UCS2LENGTH = `function ucs2length(str) {
  const len = str.length
  let length = 0, pos = 0, value
  while (pos < len) {
    length++
    value = str.charCodeAt(pos++)
    if (value >= 0xd800 && value <= 0xdbff && pos < len) {
      value = str.charCodeAt(pos)
      if ((value & 0xfc00) === 0xdc00) pos++
    }
  }
  return length
}`
export function validators(schemas, bundle) {
  // which named types have a schema URI ajv can compile on its own (roots and $defs; not inline titled ones)
  const entries = []
  for (const { schema } of schemas) {
    if (SHAPE.some((k) => k in schema)) entries.push([typeName(bundle, schema.$id, '', schema.title), schema.$id])
    for (const [key, def] of Object.entries(schema.$defs || {})) entries.push([typeName(bundle, schema.$id, `/$defs/${key}`, def.title, key), `${schema.$id}#/$defs/${key}`])
  }
  entries.sort((a, b) => (a[0] === b[0] ? a[1].localeCompare(b[1]) : a[0].localeCompare(b[0])))
  // allErrors off: a guard stops at the first problem (strict mode reports only that one), which keeps the code small.
  const ajv = makeAjv({ code: { source: true, esm: true, lines: false }, inlineRefs: false, allErrors: false })
  const exportsMap = {}   // guard name → the URI compiled for it (the first URI of each type)
  const fnOf = {}         // every URI → its guard
  for (const [name, uri] of entries) {
    const fn = guardName(name)
    if (!(fn in exportsMap)) exportsMap[fn] = uri
    fnOf[uri] = fn
  }
  let code = standaloneCode(ajv, exportsMap)
  const req = /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g
  code = code.replace(req, 'ucs2length')
  const left = code.match(/require\([^)]*\)/g)
  if (left) throw new Error(`the standalone validators still require ${[...new Set(left)].join(', ')}: inline it in scripts/gen-contract.mjs`)
  if (!code.includes(DATE_TIME.source)) throw new Error('the date-time format was not inlined')
  code = code.replace(/^"use strict";/, '')
  const byUri = entries.map(([, uri]) => uri)
  const js = `// ${HEADER}
// Ajv ${JSON.parse(fs.readFileSync(path.join(REPO, 'node_modules/ajv/package.json'), 'utf8')).version} standalone validators (draft 2020-12, the date-time format as in contract/tools/schemas.mjs).
${UCS2LENGTH}
${code}
// Every validator by its schema URI (the names contract/api/routes.json uses).
export const validators = Object.freeze({
${byUri.map((u) => `  ${JSON.stringify(u)}: ${fnOf[u]},`).join('\n')}
})
// The first way data breaks the schema at uri, or null when it conforms: strict mode's "contract violation: <schema> <path>".
export function violation(uri, data) {
  const v = validators[uri]
  if (!v) return { schema: uri, path: '', message: 'no such schema' }
  if (v(data)) return null
  const e = (v.errors || [])[0] || {}
  return { schema: uri, path: e.instancePath || '/', message: \`\${e.message || 'is invalid'}\${e.params && e.params.additionalProperty ? \` (\${e.params.additionalProperty})\` : ''}\` }
}
`
  const typeOf = Object.fromEntries(entries.map(([name, uri]) => [uri, name]))
  const dts = `// ${HEADER}
import type * as T from './types.ts'

export interface ValidationError {
  readonly instancePath: string
  readonly schemaPath: string
  readonly keyword: string
  readonly params: Readonly<Record<string, unknown>>
  readonly message?: string
}
/** A type guard: true when data matches the schema; then .errors is null, else the reasons. */
export type Validator<V> = ((data: unknown) => data is V) & { errors?: readonly ValidationError[] | null }

${Object.entries(exportsMap).map(([fn, uri]) => `/** ${uri} */\nexport declare const ${fn}: Validator<T.${typeOf[uri]}>`).join('\n')}

export type SchemaUri = ${byUri.map((u) => JSON.stringify(u)).join(' | ')}
export interface Validators {
${byUri.map((u) => `  readonly ${JSON.stringify(u)}: Validator<T.${typeOf[u]}>`).join('\n')}
}
export declare const validators: Validators
export interface Violation { readonly schema: string, readonly path: string, readonly message: string }
/** The first way data breaks the schema at uri, or null when it conforms. */
export declare function violation(uri: SchemaUri, data: unknown): Violation | null
`
  return { js, dts }
}
// Every schema URI that names a type (roots and $defs) → that type's name, e.g.
// "midstudy/library.schema.json#/$defs/item" → "LibraryItem".
export function schemaTypeNames(schemas = loadSchemas()) {
  const out = {}
  for (const { schema } of schemas) {
    if (SHAPE.some((k) => k in schema)) out[schema.$id] = typeName(null, schema.$id, '', schema.title)
    for (const [key, def] of Object.entries(schema.$defs || {})) out[`${schema.$id}#/$defs/${key}`] = typeName(null, schema.$id, `/$defs/${key}`, def.title, key)
  }
  return out
}
function typeName(bundle, id, pointer, title, key) {
  if (typeof title === 'string' && IDENT.test(title)) return title
  const file = pascal(path.basename(id))
  return pointer ? `${file}${pascal(key)}` : file
}
const guardName = (name) => `is${name}`

// --- main -----------------------------------------------------------------------------------------------------------
export function generate() {
  const schemas = loadSchemas()
  const bundle = simplifyForTypes(buildBundle(schemas))
  const { js, dts } = validators(schemas, bundle)
  return {
    [OUT.types]: typescript(bundle),
    [OUT.validate]: js,
    [OUT.validateDts]: dts,
    [OUT.bundle]: `${JSON.stringify(forRust(bundle), null, 2)}\n`,
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check')
  const files = generate()
  let drift = 0
  for (const [file, text] of Object.entries(files)) {
    const rel = path.relative(REPO, file)
    const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null
    if (check) {
      if (old !== text) { drift++; console.error(`gen-contract: ${rel} is out of date (run node scripts/gen-contract.mjs)`) }
    } else if (old !== text) {
      fs.mkdirSync(path.dirname(file), { recursive: true })
      fs.writeFileSync(file, text)
      console.log(`gen-contract: wrote ${rel}`)
    }
  }
  const n = Object.keys(JSON.parse(files[OUT.bundle]).definitions).length
  console.log(`gen-contract: ${n} types from ${loadSchemas().length} schemas${check ? (drift ? `, ${drift} file(s) out of date` : ', up to date') : ''}`)
  process.exit(drift ? 1 : 0)
}
