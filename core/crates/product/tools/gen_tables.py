"""Writes src/tables.rs: the character classes of Python 3.12's `re` that v1's product reader relied on (Unicode
15.0.0), so the Rust reader classifies every character exactly as v1 did:

  PY_WORD   `\\w` in a str pattern (str.isalnum() or "_"): what `\\b` looks at
  PY_DIGIT  `\\d` (Unicode Nd), each run starting at the digit zero (so a digit's value is (c - start) % 10, which is
            also what float() and int() read)
  PY_SPACE  `\\s` and str.isspace()

Run it with the dev shell's Python (the one v1 ran on): `nix develop -c python3 core/crates/product/tools/gen_tables.py`.
"""
import pathlib
import re
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        ok = pred(c)
        if ok and start is None:
            start = c
        if not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


word = ranges(lambda c: re.match(r"\w", chr(c)) is not None)
digit = ranges(lambda c: re.match(r"\d", chr(c)) is not None)
space = [c for c in range(0x110000) if chr(c).isspace()]
assert all(unicodedata.digit(chr(a), -1) == 0 and (b - a + 1) % 10 == 0 for a, b in digit)
assert space == [c for c in range(0x110000) if re.match(r"\s", chr(c))]

def table(name, rs, doc):
    rows = ",\n".join(f"    (0x{a:04X}, 0x{b:04X})" for a, b in rs)
    return f"/// {doc}\npub(crate) const {name}: &[(u32, u32)] = &[\n{rows},\n];\n"

out = [
    "// Generated by tools/gen_tables.py from Python " + sys.version.split()[0] + " (Unicode " + unicodedata.unidata_version + "); do not edit.\n#![allow(clippy::unreadable_literal)]\n",
    table("PY_WORD", word, "Python's `\\w` (str patterns): inclusive code point ranges, sorted."),
    table("PY_DIGIT", digit, "Python's `\\d` (Unicode Nd): inclusive ranges, each starting at a digit zero."),
    "/// Python's `\\s` (`str.isspace()`), sorted.\npub(crate) const PY_SPACE: &[u32] = &[" + ", ".join(f"0x{c:04X}" for c in space) + "];\n",
]
path = pathlib.Path(__file__).resolve().parent.parent / "src" / "tables.rs"
path.write_text("\n".join(out))
print(f"{path}: {len(word)} word ranges, {len(digit)} digit ranges, {len(space)} spaces")
