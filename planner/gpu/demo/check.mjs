// --- v2: the demo on each backend -------------------------------------------------------------------------------------------
async function openDemo(backend, extra = '') {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } })
  const page = await ctx.newPage()
  const errors = []
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text().slice(0, 300)) })
  page.on('pageerror', (e) => errors.push(String(e.stack || e).slice(0, 500)))
  await page.goto(`${stat.base}/demo/index.html?backend=${backend}${extra}`)
  const info = await page.evaluate(async () => { const d = window.gpuDemo; const i = await d.ready; const s = await d.openScene('/scene'); return { ...i, scene: s } }).catch((e) => ({ error: String(e.message || e).split('\n')[0] }))
  return { page, ctx, errors, info }
}

