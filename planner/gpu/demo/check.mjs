async function v1Case(page, name, c) {
  await hook(page, 'clearItems')
  await hook(page, 'setOcclusion', [c.occlusion])
  await hook(page, 'setRenderSettings', [{ contactShadows: c.contact }])
  await hook(page, 'setLighting', [{ cast_shadows: c.cast }])
  const uids = []
  for (const it of c.items) { const a = await hook(page, 'addItem', [it.id, { position: it.spec.position, rotation_y_deg: 0 }], 120000); uids.push(a.value ?? a.error) }
  if (name !== 'order') await sleep(500) // order: render right after placing (E13)
  const r = await hook(page, 'renderView', [{ model: 'nano-banana' }], 240000)
  const file = r.value?.name ? path.join(srv.dirs.renders, `${r.value.name}-input.jpg`) : null
  return { file, error: r.error, uids }
}

async function v2Case(page, tag, name, c) {
  const res = await page.evaluate(async ({ c, name }) => {
    const d = window.gpuDemo
    d.clearItems()
    d.setOcclusion(c.occlusion); d.setContactShadows(c.contact); d.setCastShadows(c.cast)
    const added = []
    for (const [i, it] of c.items.entries()) added.push(await d.addItem({ uid: `${name}-${i}`, ...it.spec }))
    const shot = await d.capture()
    return { added, shot }
  }, { c, name }).catch((e) => ({ error: String(e.message || e).split('\n')[0] }))
  if (res.error) return { error: res.error }
  const file = path.join(ev.out, `${tag}-${name}.png`)
  fs.writeFileSync(file, Buffer.from(res.shot.dataUrl.split(',')[1], 'base64'))
  return { file, added: res.added, ms: res.shot.ms, size: [res.shot.width, res.shot.height] }
}

// E13/E4/E16's judgements of one renderer's composites
function judge(tag, shots) {
  const out = {}
  const s = shots.size, sp = CASES.size.items[0]
  if (s?.file) {
    const wb = boxAt(sp.spec.position, sp.dims), r = rectOf(wb)
    const d = pyHelper(['drawn', '--composite', s.file, '--photo', LW.photo, `--window=${[r[0] - 120, r[1] - 120, r[2] + 120, r[3] + 120].join(',')}`, '--debug', path.join(ev.out, `dbg-${tag}-size-drawn.png`)])
    const tol = [Math.max(6, 0.03 * (r[2] - r[0])), Math.max(6, 0.03 * (r[3] - r[1]))]
    ev.check(`${tag}: the splat probe is drawn where its box projects, every edge within 3 % (or 6 px)`, edgeOk(d.bbox, r, tol), d.error || fmt({ drawn: d.bbox?.map(Math.round), projected: r.map(Math.round), tol: tol.map(Math.round) }))
    const o = pyHelper(['occlusion', '--composite', s.file, '--photo', LW.photo, '--camera', JSON.stringify(CAM), '--box', JSON.stringify([wb.min, wb.max])])
    ev.check(`${tag}: the splat probe is magenta inside its silhouette (≥ 90 %), not its green stand-in`, o.visible_magenta >= 0.9, o.error || `${pct(o.visible_magenta)} of ${o.n_visible} px`)
    out.size = { drawn: d.bbox, projected: r, magenta: o.visible_magenta }
  } else ev.check(`${tag}: size case rendered`, false, s?.error || 'no file')
  const i = shots.idol, ip = CASES.idol.items[0]
  if (i?.file) {
    const wb = boxAt(ip.spec.position, ip.dims), r = rectOf(wb)
    const d = pyHelper(['drawn', '--composite', i.file, '--photo', LW.photo, `--window=${[r[0] - 150, r[1] - 150, r[2] + 150, r[3] + 150].join(',')}`, '--debug', path.join(ev.out, `dbg-${tag}-idol-drawn.png`)])
    const pj = pyHelper(['splat-proj', '--spz', idolSpz, '--camera', JSON.stringify(CAM), `--position=${JSON.stringify(ip.spec.position)}`, '--rotation-y-deg', '0', '--width', String(W), '--height', String(H)])
    const pb = pj.bbox
    const tol = pb ? [Math.max(8, 0.05 * (pb[2] - pb[0])), Math.max(8, 0.05 * (pb[3] - pb[1]))] : [0, 0]
    const iw = r[2] - r[0], ih = r[3] - r[1]
    const ok = d.bbox && pb && edgeOk(d.bbox, pb, tol) && d.bbox[0] >= r[0] - 0.03 * iw && d.bbox[2] <= r[2] + 0.03 * iw && d.bbox[1] >= r[1] - 0.03 * ih && d.bbox[3] <= r[3] + 0.03 * ih
    ev.check(`${tag}: the Idol chair (262,144 splats) is drawn where its splat.spz points project, every edge within 5 % (or 8 px), inside its box (+3 %)`, ok,
      d.error || pj.error || fmt({ drawn: d.bbox?.map(Math.round), splat_points: pb?.map(Math.round), box: r.map(Math.round) }))
    out.idol = { drawn: d.bbox, points: pb, box: r }
  } else ev.check(`${tag}: idol case rendered`, false, i?.error || 'no file')
  const o = shots.order
  if (o?.file) {
    const wb = boxAt(CASES.order.items[0].spec.position, CASES.order.items[0].dims)
    const a = pyHelper(['occlusion', '--composite', o.file, '--photo', LW.photo, '--camera', JSON.stringify(CAM), '--box', JSON.stringify([wb.min, wb.max])])
    ev.check(`${tag}: right after placing, the near splat is in front of the far one (≥ 90 % magenta over the probe)`, a.visible_magenta >= 0.9, a.error || `${pct(a.visible_magenta)} of ${a.n_visible} px`)
    out.order = a.visible_magenta
  } else ev.check(`${tag}: order case rendered`, false, o?.error || 'no file')
  const on = shots.occl, off = shots.occlOff
  if (on?.file && off?.file) {
    const wb = boxAt(CASES.occl.items[0].spec.position, CASES.occl.items[0].dims)
    const a = pyHelper(['occlusion', '--composite', on.file, '--photo', LW.photo, '--camera', JSON.stringify(CAM), '--box', JSON.stringify([wb.min, wb.max]), '--depth', LW.depth, '--debug', path.join(ev.out, `dbg-${tag}-occl-on.png`)])
    const b = pyHelper(['occlusion', '--composite', off.file, '--photo', LW.photo, '--camera', JSON.stringify(CAM), '--box', JSON.stringify([wb.min, wb.max]), '--depth', LW.depth])
    ev.check(`${tag}: the sofa hides the splat behind it: hidden pixels match the photo (≥ 95 %), the part above shows (≥ 85 %)`, a.hidden_match >= 0.95 && a.visible_magenta >= 0.85 && a.n_hidden > 5000,
      a.error || `${pct(a.hidden_match)} match of ${a.n_hidden}, ${pct(a.visible_magenta)} magenta of ${a.n_visible}`)
    ev.check(`${tag}: occlusion off shows the hidden part (≥ 85 % magenta)`, b.hidden_magenta >= 0.85, b.error || `${pct(b.hidden_magenta)}`)
    out.occl = { hidden_match: a.hidden_match, visible: a.visible_magenta, off: b.hidden_magenta }
  } else ev.check(`${tag}: occlusion cases rendered`, false, on?.error || off?.error || 'no file')
  const l = shots.lit
  if (l?.file) {
    const wb = boxAt(CASES.lit.items[0].spec.position, CASES.lit.items[0].dims)
    const m = pyHelper(['lighting', '--composite', l.file, '--photo', LW.photo, '--camera', JSON.stringify(CAM), '--box', JSON.stringify([wb.min, wb.max]), '--lighting', path.join(LW.dir, 'lighting.json'),
      '--light', JSON.stringify(JSON.parse(fs.readFileSync(path.join(LW.dir, 'lighting.json'), 'utf8')).world.key_direction), '--depth', LW.depth, '--debug', path.join(ev.out, `dbg-${tag}-lit.png`)])
    const faces = Object.entries(m.faces || {})
    ev.check(`${tag}: the lit box's visible faces are within 12 % of lighting.json's radiance (E16)`, faces.length >= 2 && faces.every(([, f]) => Math.abs(f.ratio - 1) <= 0.12),
      m.error || fmt(Object.fromEntries(faces.map(([k, f]) => [k, { rgb: f.rgb, expected: f.expected_rgb, ratio: f.ratio }]))))
    ev.check(`${tag}: its floor shadow falls away from the light (within 35°)`, m.shadow?.offset_vs_light_deg != null && m.shadow.offset_vs_light_deg <= 35, m.error || fmt(m.shadow))
    out.lit = { faces: Object.fromEntries(faces.map(([k, f]) => [k, f.rgb])), shadow: m.shadow }
  }
  const photoOk = Object.values(shots).filter((x) => x?.file).map((x) => pyHelper(['region-diff', '--a', x.file, '--b', LW.photo, '--rects', JSON.stringify([[0, 0, 300, 300], [1300, 0, 1600, 200]])]))
  ev.check(`${tag}: the photo is drawn as is away from the furniture (corners, mean ≤ 2 in every case)`, photoOk.length > 0 && photoOk.every((r) => r.mean != null && r.mean <= 2), fmt(photoOk.map((r) => r.mean)))
  return out
}

// region by region against v1's composite of the same case
function compare(tag, shots, ref) {
  const rows = {}
  for (const [name, c] of Object.entries(CASES)) {
    const a = shots[name]?.file, b = ref[name]?.file
    if (!a || !b) continue
    const rects = c.items.map((it) => rectOf(boxAt(it.spec.position, it.dims), 12))
    const shadowRects = c.cast || c.contact ? c.items.map((it) => { const r = rectOf(boxAt(it.spec.position, it.dims)); return [r[0] - 150, r[3] - 60, r[2] + 150, r[3] + 120] }) : []
    rows[name] = {
      items: pyHelper(['region-diff', '--a', a, '--b', b, '--rects', JSON.stringify(rects)]),
      ...(shadowRects.length ? { floor: pyHelper(['region-diff', '--a', a, '--b', b, '--rects', JSON.stringify(shadowRects)]) } : {}),
      photo: pyHelper(['region-diff', '--a', a, '--b', b, '--rects', JSON.stringify([[0, 0, 300, 300], [1300, 0, 1600, 200]])]),
    }
  }
  const r = (v) => (v == null ? 'n/a' : v.toFixed(2))
  for (const [name, row] of Object.entries(rows)) {
    const lim = ['size', 'idol', 'order', 'occl', 'occlOff', 'litSplat', 'castSplat'].includes(name) ? { mean: 6, p99: 80 } : { mean: 3, p99: 40 }
    ev.check(`${tag} vs v1, ${name}: the items' region (mean ≤ ${lim.mean}, p99 ≤ ${lim.p99})${row.floor ? ', the floor around them (mean ≤ 3)' : ''}, the photo`,
      row.items.mean != null && row.items.mean <= lim.mean && row.items.p99 <= lim.p99 && (!row.floor || row.floor.mean <= 3) && row.photo.mean <= 2,
      `items mean ${r(row.items.mean)} p99 ${r(row.items.p99)}${row.floor ? `, floor mean ${r(row.floor.mean)} p99 ${r(row.floor.p99)}` : ''}, photo mean ${r(row.photo.mean)}`)
  }
  return rows
}

